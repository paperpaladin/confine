#!/bin/sh
# Generate the capability name table from the kernel header.
#
# Typed by hand this table rots: a kernel that adds CAP_ANYTHING turns a
# set bit into "cap 41" and nobody notices, because nothing fails. Derived
# from the header, the build simply picks the new name up.
#
# Only lines of the exact shape "#define CAP_NAME <number>" count.
# CAP_LAST_CAP is an alias for another capability and CAP_TO_INDEX and
# CAP_TO_MASK are macros, so the pattern requires a bare decimal.
set -e

HDR=${1:-/usr/include/linux/capability.h}

[ -r "$HDR" ] || {
	echo "mkcaps: cannot read $HDR" >&2
	echo "  the capability names come from the kernel headers, so this" >&2
	echo "  needs kernel-headers (Fedora) or linux-libc-dev (Debian)." >&2
	exit 1
}

n=$(grep -cE '^#define[[:blank:]]+CAP_[A-Z0-9_]+[[:blank:]]+[0-9]+[[:blank:]]*$' "$HDR")
[ "$n" -gt 0 ] || { echo "mkcaps: no capabilities found in $HDR" >&2; exit 1; }

printf '/* Generated by mkcaps.sh from %s. Do not edit. */\n' "$HDR"
printf 'static const char *const CAP_NAME[] = {\n'
grep -E '^#define[[:blank:]]+CAP_[A-Z0-9_]+[[:blank:]]+[0-9]+[[:blank:]]*$' "$HDR" |
	sed -E 's/^#define[[:blank:]]+CAP_([A-Z0-9_]+)[[:blank:]]+([0-9]+)[[:blank:]]*$/\2 \1/' |
	sort -n |
	awk '{ printf "\t[%s] = \"%s\",\n", $1, tolower($2) }'
printf '};\n'
printf '#define CAP_COUNT %d\n' "$n"
